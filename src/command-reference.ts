/**
 * The Markdown command reference in docs/commands.md: gunshi's own help for
 * the program and each command, rendered by `generate()` with the options the
 * CLI runs with, so the page reads exactly like `--help`.
 */

/**
 * Builds the command reference from `render`, which returns the help text for
 * a command name, or for the program when given null. The page names no
 * version, so a release does not make it stale.
 *
 * @evidence docs/spec.md#command-reference Builds docs/commands.md from gunshi's generated help for the program and every command, in definition order, without a version.
 * @evidenceReview docs/spec.md#command-reference #fac00cd Reread the new section; this renders the program and every command through the given generate() call in definition order, fences each, and writes no version.
 */
export async function commandReference(
  program: string,
  commands: readonly string[],
  render: (command: string | null) => Promise<string>,
): Promise<string> {
  const sections = [
    `## ${program}\n\n${fence(await render(null))}`,
    ...(await Promise.all(
      commands.map(async (name) => `## ${program} ${name}\n\n${fence(await render(name))}`),
    )),
  ];
  return [
    '# Command reference',
    '',
    `<!-- Generated by \`pnpm docs:commands\` from the command definitions; do not edit by hand. -->`,
    '',
    `Every command prints JSON on stdout. This page is \`${program} --help\` and \`${program} <command> --help\` for each command.`,
    '',
    sections.join('\n\n'),
    '',
  ].join('\n');
}

function fence(text: string): string {
  const body = text.replace(/\r\n/g, '\n').replace(/\s+$/u, '');
  return `\`\`\`text\n${body}\n\`\`\``;
}
